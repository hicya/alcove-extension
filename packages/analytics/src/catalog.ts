/**
 * Typed analytics event catalogs, shared by every Hicya app and transport.
 *
 * Privacy rule: an event parameter is a fixed enum member, a boolean, a non-negative whole
 * number or a system-generated id. Never text a person typed or chose (titles, names, notes,
 * search queries, URLs, emails). Each app declares its events once with
 * `defineAnalyticsEvents`, and every transport sends only what `catalog.event` returns, so a
 * cast cannot smuggle text past the types.
 */

export type ParamSpec =
  | { readonly kind: "enum"; readonly values: readonly string[] }
  | { readonly kind: "boolean" }
  | { readonly kind: "count" }
  | { readonly kind: "id" };

export type EventSpecs = Readonly<Record<string, Readonly<Record<string, ParamSpec>>>>;

export type AnalyticsParamValue = string | number | boolean;

/** A validated event, ready for gtag, Firebase or the Measurement Protocol. */
export interface AnalyticsEvent<Name extends string = string> {
  readonly name: Name;
  readonly params: Readonly<Record<string, AnalyticsParamValue>>;
}

type ParamValue<S> = S extends { kind: "enum"; values: readonly (infer V)[] }
  ? V
  : S extends { kind: "boolean" }
    ? boolean
    : S extends { kind: "count" | "id" }
      ? S extends { kind: "count" }
        ? number
        : string
      : never;

export type EventParams<Specs extends EventSpecs, N extends keyof Specs> = {
  readonly [K in keyof Specs[N]]: ParamValue<Specs[N][K]>;
};

/** Events without parameters may omit the params argument. */
export type EventArgs<Specs extends EventSpecs, N extends keyof Specs> = [keyof Specs[N]] extends [
  never,
]
  ? [params?: Readonly<Record<string, never>>]
  : [params: EventParams<Specs, N>];

export class AnalyticsEventError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "AnalyticsEventError";
  }
}

/** Google Analytics limits: names start with a letter, 40 characters, no reserved prefixes. */
const ANALYTICS_NAME = /^[A-Za-z][A-Za-z0-9_]{0,39}$/;
const RESERVED_PREFIXES = ["firebase_", "google_", "ga_"];
/** Events Google Analytics reserves for itself on at least one platform. */
const RESERVED_EVENTS = new Set([
  "ad_activeview",
  "ad_click",
  "ad_exposure",
  "ad_impression",
  "ad_query",
  "adunit_exposure",
  "app_clear_data",
  "app_install",
  "app_remove",
  "app_update",
  "error",
  "first_open",
  "first_visit",
  "in_app_purchase",
  "notification_dismiss",
  "notification_foreground",
  "notification_open",
  "notification_receive",
  "os_update",
  "screen_view",
  "session_start",
  "user_engagement",
]);
const MAX_PARAMETERS = 25;
/** An id is generated by the system (uuid, cuid, slug, number), never typed by a person. */
const ID_VALUE = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;

export function assertAnalyticsName(name: string, kind: "event" | "parameter"): void {
  if (!ANALYTICS_NAME.test(name)) {
    throw new AnalyticsEventError(
      `Invalid analytics ${kind} name "${name}". Use 1-40 letters, numbers or underscores, starting with a letter.`,
    );
  }
  if (RESERVED_PREFIXES.some((prefix) => name.startsWith(prefix))) {
    throw new AnalyticsEventError(`Analytics ${kind} name "${name}" uses a reserved prefix.`);
  }
  if (kind === "event" && RESERVED_EVENTS.has(name)) {
    throw new AnalyticsEventError(`Analytics event name "${name}" is reserved by Google.`);
  }
}

function validateParam(
  event: string,
  key: string,
  spec: ParamSpec,
  value: unknown,
): AnalyticsParamValue {
  switch (spec.kind) {
    case "enum":
      if (typeof value !== "string" || !spec.values.includes(value)) {
        throw new AnalyticsEventError(`${event}.${key} must be one of: ${spec.values.join(", ")}.`);
      }
      return value;
    case "boolean":
      if (typeof value !== "boolean") {
        throw new AnalyticsEventError(`${event}.${key} must be a boolean.`);
      }
      return value;
    case "count":
      if (typeof value !== "number" || !Number.isSafeInteger(value) || value < 0) {
        throw new AnalyticsEventError(`${event}.${key} must be a non-negative whole number.`);
      }
      return value;
    case "id":
      if (typeof value !== "string" || !ID_VALUE.test(value)) {
        throw new AnalyticsEventError(
          `${event}.${key} must be a system-generated id (letters, digits, - or _, at most 64).`,
        );
      }
      return value;
  }
}

export interface AnalyticsCatalog<Specs extends EventSpecs> {
  readonly specs: Specs;
  isEventName(name: string): name is Extract<keyof Specs, string>;
  /** Runtime check for an event from any source. Throws `AnalyticsEventError`. */
  validate(name: string, params?: unknown): AnalyticsEvent<Extract<keyof Specs, string>>;
  /** Typed entry point for senders. The runtime check still runs. */
  event<N extends Extract<keyof Specs, string>>(
    name: N,
    ...args: EventArgs<Specs, N>
  ): AnalyticsEvent<N>;
}

/**
 * Declares an app's events. Names and parameter keys are checked against Google Analytics'
 * rules once, here, so a bad catalog fails at startup and in tests rather than in production.
 */
export function defineAnalyticsEvents<const Specs extends EventSpecs>(
  specs: Specs,
): AnalyticsCatalog<Specs> {
  const table = new Map<string, Readonly<Record<string, ParamSpec>>>(Object.entries(specs));
  for (const [name, params] of table) {
    assertAnalyticsName(name, "event");
    const keys = Object.keys(params);
    if (keys.length > MAX_PARAMETERS) {
      throw new AnalyticsEventError(
        `${name} declares more than ${String(MAX_PARAMETERS)} parameters.`,
      );
    }
    for (const key of keys) assertAnalyticsName(key, "parameter");
  }

  function isEventName(name: string): name is Extract<keyof Specs, string> {
    return table.has(name);
  }

  function validate(name: string, params: unknown = {}) {
    if (!isEventName(name)) throw new AnalyticsEventError(`Unknown analytics event "${name}".`);
    if (typeof params !== "object" || params === null || Array.isArray(params)) {
      throw new AnalyticsEventError(`${name} parameters must be an object.`);
    }
    const given = new Map<string, unknown>(Object.entries(params));
    const validated: Record<string, AnalyticsParamValue> = {};
    for (const [key, spec] of Object.entries(table.get(name) ?? {})) {
      if (!given.has(key)) throw new AnalyticsEventError(`${name}.${key} is required.`);
      validated[key] = validateParam(name, key, spec, given.get(key));
      given.delete(key);
    }
    const extra = [...given.keys()];
    if (extra.length > 0) {
      throw new AnalyticsEventError(`${name} does not accept: ${extra.join(", ")}.`);
    }
    return { name, params: validated };
  }

  return {
    specs,
    isEventName,
    validate,
    event(name, ...args) {
      const validated = validate(name, args[0] ?? {});
      return { name, params: validated.params };
    },
  };
}

export const COUNT_BUCKETS = ["0", "1-9", "10-99", "100+"] as const;
export type CountBucket = (typeof COUNT_BUCKETS)[number];

/** Coarse size for counts that could otherwise single someone out. */
export function countBucket(count: number): CountBucket {
  if (!Number.isFinite(count) || count <= 0) return "0";
  if (count < 10) return "1-9";
  if (count < 100) return "10-99";
  return "100+";
}

/** Shorthands for catalog declarations. */
export const param = {
  enum: <const V extends readonly string[]>(values: V) => ({ kind: "enum", values }) as const,
  boolean: { kind: "boolean" } as const,
  count: { kind: "count" } as const,
  id: { kind: "id" } as const,
};
